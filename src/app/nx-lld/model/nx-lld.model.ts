// LLD configuration: View -> Groups -> Sub-groups -> Equipments.
// CamelCase for everything this screen owns — those APIs aren't known yet
// (the service runs on a mock, see NxLldService). Subsurfaces and stations
// are the host's own dcTag (model/dc-tag.model.ts).

// The host's result envelope. A failed call can still be an HTTP 200 —
// Status/IsValid say whether it worked, ErrorMessage/StatusMessage why not.
export interface LldApiStatus {
  IsValid: boolean;
  Status: boolean;
  StatusMessage: string | null;
  ErrorMessage: string | null;
  // The saved record's id when the API reports one (0 otherwise).
  ID?: number | null;
}

// An envelope carrying a payload (GetSubSurfaceOperations does; GetStations
// returns a bare array, SaveLD an envelope with no Value).
export interface LldApiResult<T> extends LldApiStatus {
  Value: T;
}

// What SaveLD is posted — a new view has no LDID, an edit (or delete) has
// it. No CreatedBy / ModifiedBy: the API stamps who saved it.
export interface LldSaveViewRequest {
  LDID?: number;
  LDViewName: string;
  LDDescription: string;
  SubSurfaceOperationId: number;
  SubSurfaceOperation: string;
  // The selected stations' names, comma-separated.
  Facility: string;
  Status: LldViewStatus;
}

// One row of GetLDViews' Value. Older rows can have SubSurfaceOperationId 0
// and SubSurfaceOperation null; ModifiedBy is 0 until the view is edited.
// CreatedOn/ModifiedOn weren't in the sample — read when the API sends them.
export interface LldViewResponse {
  LDID: number;
  LDViewName: string;
  LDDescription: string | null;
  SubSurfaceOperationId: number | null;
  SubSurfaceOperation: string | null;
  Facility: string | null;
  Status: LldViewStatus;
  CreatedBy: number | string | null;
  CreatedOn?: string | null;
  ModifiedBy: number | string | null;
  ModifiedOn?: string | null;
  [key: string]: unknown;
}

// ---------------------------------------------------------------- lookups
// The Sub-group popup's dropdown values, delivered by ONE call
// (getLookups()) — assets/mock-api/lld-lookups.json for now. Lookup ids are
// strings; record ids (below) are server-assigned numbers.
export interface LldLookups {
  subGroupTypes: LldSubGroupType[];
  equipments: LldOption[];
}

export interface LldOption {
  id: string;
  name: string;
}

// The Sub-group popup's Type dropdown; picking one loads its template
// versions into the Template dropdown.
export interface LldSubGroupType extends LldOption {
  templates: LldTemplate[];
}

export interface LldTemplate extends LldOption {
  version: string;
}

// ---------------------------------------------------------------- records
// `id` is assigned by the SERVER — absent on a new record's save payload,
// present on an edit's (same save URL either way). Never generated by the UI.

// Sent to the server as the number. Deleted is a soft delete: set only by
// the Delete button (NxLldService.deleteView, a SaveLD with Status 3) — the record stays in the
// database but is never listed again.
export enum LldViewStatus {
  Private = 1,
  Public = 2,
  Deleted = 3
}

// What the View popup's Status dropdown offers — Deleted isn't pickable.
export const LLD_VIEW_STATUS_OPTIONS: { value: LldViewStatus; label: string }[] = [
  { value: LldViewStatus.Private, label: "Private" },
  { value: LldViewStatus.Public, label: "Public" }
];

export interface LldView {
  id?: number | null;
  name: string;
  // The subsurface tag's ObjectID and TagName — both are saved.
  subsurfaceId: number | null;
  subsurfaceName: string;
  // Selected stations' names (their tags' TagName) — all from that
  // subsurface's own station list (getStations()). Saved comma-separated.
  stationNames: string[];
  // Audit info, set by the server and shown on the view card. createdBy is
  // also sent back on an edit. modifiedBy/modifiedOn stay empty until the
  // view is first edited. Dates are ISO strings.
  createdBy?: string | null;
  createdOn?: string | null;
  modifiedBy?: string | null;
  modifiedOn?: string | null;
  status: LldViewStatus;
  description: string;
}

export interface LldGroup {
  id?: number | null;
  viewId: number;
  name: string;
  description: string;
  // Display order within the view (lowest first).
  order: number;
  // A Group Type option's value — its position in the configured list
  // (see parseGroupTypes()), null when none is picked.
  type: number | null;
  isVisible: boolean;
  // Set only by Delete (a SaveLDGroup with IsDeleted true).
  isDeleted?: boolean;
}

// What SaveLDGroup is posted — add (GroupID 0), edit (the real GroupID) AND
// delete (an edit with IsDeleted true), same URL. GetLDGroupDetails returns
// rows of the same shape.
export interface LldGroupRequest {
  GroupID: number;
  GroupName: string;
  LDID: number;
  GroupOrder: number;
  GroupDesc: string;
  GroupType: number | null;
  IsVisible: boolean;
  IsDeleted: boolean;
}

// One Group Type dropdown option.
export interface LldGroupTypeOption {
  value: number;
  label: string;
}

// The Group Type names, comma-separated — the host's configuration
// (e.g. "Pump,Separator,Equipment"). Placeholder names until it's set.
export const LLD_DEFAULT_GROUP_TYPES = "a,b,c,d";

// The configured names as dropdown options. The value sent as GroupType is
// the name's 1-based position: "Pump,Separator" -> Pump = 1, Separator = 2 —
// so only ever append to the list, never reorder it.
export function parseGroupTypes(names: string | null | undefined): LldGroupTypeOption[] {
  return (names ?? "")
    .split(",")
    .map((label, i) => ({ value: i + 1, label: label.trim() }))
    .filter(o => o.label);
}

// One sub-group = ONE type + ONE template for every equipment in it —
// mixed templates aren't representable, by design.
export interface LldSubGroup {
  id?: number | null;
  groupId: number;
  name: string;
  typeId: string;
  templateId: string;
  // At least one; the same equipment never twice.
  equipments: LldSubGroupEquipment[];
}

// One equipment in a sub-group, with the meta information entered for it.
export interface LldSubGroupEquipment {
  // Which lookup equipment this is.
  equipmentId: string;
  // Pre-filled from the equipment's own name, editable. Required.
  name: string;
  path: string;
  attribute: string;
}

// What getGroups(viewId) returns: each group with its own sub-groups, so
// the grouped layout renders from a single call.
export interface LldGroupWithSubGroups extends LldGroup {
  subGroups: LldSubGroup[];
}
