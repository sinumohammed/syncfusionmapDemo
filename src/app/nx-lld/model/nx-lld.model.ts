// The configured Group Types as dropdown options (label TYPES, value
// TypeID) — the array, or the same as a JSON string. Rows without a name or
// a numeric TypeID are skipped.
export function parseGroupTypes(types: LldGroupType[] | string | null | undefined): LldGroupTypeOption[] {
  let rows: unknown = types;
  if (typeof types === "string") {
    try {
      rows = JSON.parse(types);
    } catch {
      console.error("[LLD] Group types aren't valid JSON:", types);
      return [];
    }
  }
  return (Array.isArray(rows) ? (rows as Partial<LldGroupType>[]) : [])
    .map(row => ({ value: Number(row?.TypeID), label: String(row?.TYPES ?? "").trim() }))
    .filter(o => o.label && Number.isFinite(o.value));
}

// One sub-group = ONE type + ONE template for every equipment in it —
// mixed templates aren't representable, by design.
export interface LldSubGroup {
  id?: number | null;
  groupId: number;
  name: string;
  typeId: string;
  templateId: string;
  // At least one; the same equipment never twice.
  equipments: LldSubGroupEquipment[];
}

// One equipment in a sub-group, with the meta information entered for it.
export interface LldSubGroupEquipment {
  // Which lookup equipment this is.
  equipmentId: string;
  // Pre-filled from the equipment's own name, editable. Required.
  name: string;
  path: string;
  attribute: string;
}

// What getGroups(viewId) returns: each group with its own sub-groups, so
// the grouped layout renders from a single call.
export interface LldGroupWithSubGroups extends LldGroup {
  subGroups: LldSubGroup[];
}
